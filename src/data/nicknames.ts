export type Nickname = typeof NICKNAMES[number];

/**
 * Normalizes a nickname for case-insensitive, whitespace-trimmed comparison.
 */
export function normalizeNickname(name: string): string {
  return (name || "").trim().toLowerCase();
}

/**
 * Checks if a nickname is already in use within a room or lobby (case-insensitive).
 */
export function isNicknameTaken(name: string, takenNames: readonly string[] | string[]): boolean {
  const norm = normalizeNickname(name);
  if (!norm) return false;
  return takenNames.some((taken) => normalizeNickname(taken) === norm);
}

/**
 * Picks a random nickname from the predefined 200 nicknames, excluding any already taken.
 */
export function getRandomNickname(excludeNames: readonly string[] | string[] = []): string {
  const normalizedExclude = new Set(excludeNames.map(normalizeNickname));
  const available = NICKNAMES.filter((n) => !normalizedExclude.has(normalizeNickname(n)));
  const pool = available.length > 0 ? available : NICKNAMES;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

